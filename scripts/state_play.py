#!/usr/bin/env python3
"""Render a state-first dungeon dream and a real-vs-dream video.

    python3 scripts/state_play.py --episode 7 --steps 720 --out /tmp/dungeon8/play

The avatar is generated by the learned transition model; the cave, enemies,
diamonds and exit come from the observed state. The frame is drawn by the
known renderer, so pixels are exact and only the avatar can drift.
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dungeon_env import Dungeon, DELTA, GRID  # noqa: E402
from state_model import AvatarNet  # noqa: E402

FRAME_BYTES = 3 * 64 * 64


def renderer(wall: np.ndarray) -> Dungeon:
    dungeon = Dungeon.__new__(Dungeon)
    dungeon.grid = wall
    dungeon.player = (0, 0)
    dungeon.enemies = []
    dungeon.diamonds = []
    dungeon.goal = (0, 0)
    dungeon.start = (0, 0)
    dungeon.hits = 0
    dungeon.caught = 0
    dungeon.collected = 0
    yy, xx = np.mgrid[0:GRID, 0:GRID]
    dungeon.px = xx.astype(np.float32)
    dungeon.py = yy.astype(np.float32)
    dungeon.rng = np.random.default_rng(0)
    return dungeon


def features(player, wall, action: int) -> np.ndarray:
    out = np.zeros(13, dtype=np.float32)
    x, y = player
    out[0], out[1] = x / GRID, y / GRID
    out[2 + action] = 1.0
    out[7] = wall[y, x]
    for index, (dx, dy) in enumerate(DELTA):
        if index != action:
            continue
        tx, ty = min(GRID - 1, max(0, x + dx)), min(GRID - 1, max(0, y + dy))
        out[8] = wall[ty, tx]
    for index, (dx, dy) in enumerate(DELTA[1:]):
        nx, ny = min(GRID - 1, max(0, x + dx)), min(GRID - 1, max(0, y + dy))
        out[9 + index] = wall[ny, nx]
    return out


def entities(state: np.ndarray, offset: int, count: int) -> list[tuple[int, int]]:
    out = []
    for index in range(count):
        x, y = int(state[offset + 2 * index]), int(state[offset + 2 * index + 1])
        if x != 255:
            out.append((x, y))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, default=Path("/home/adeerkhan/tmp/dungeon8/data"))
    ap.add_argument("--model", type=Path, default=Path("/home/adeerkhan/tmp/dungeon8/state/avatar-model.pt"))
    ap.add_argument("--episode", type=int, default=7)
    ap.add_argument("--steps", type=int, default=720)
    ap.add_argument("--out", type=Path, default=Path("/home/adeerkhan/tmp/dungeon8/play"))
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    import json
    meta = json.loads((args.data / "meta.json").read_text())
    steps = int(meta["steps"])
    episodes = int(meta["episodes"])
    states = np.memmap(args.data / "state.bin", dtype=np.uint8, mode="r").reshape(episodes, steps + 1, 28)
    actions = np.memmap(args.data / "actions.bin", dtype=np.uint8, mode="r").reshape(episodes, steps)
    walls = np.memmap(args.data / "walls.bin", dtype=np.uint8, mode="r").reshape(episodes, GRID, GRID)
    frames = np.memmap(args.data / "frames.bin", dtype=np.uint8, mode="r").reshape(-1, 64, 64, 3)

    model = AvatarNet()
    model.load_state_dict(torch.load(args.model))
    model.eval()
    wall = walls[args.episode]
    if wall.shape != (GRID, GRID):
        raise SystemExit("unexpected wall shape")
    draw = renderer(wall)
    state = states[args.episode, 0]
    player = (int(state[0]), int(state[1]))
    exact = 0
    base = args.episode * (steps + 1)
    for step in range(args.steps):
        real = frames[base + step]
        action = int(actions[args.episode, step])
        with torch.no_grad():
            prediction = model(torch.from_numpy(features(player, wall, action)).unsqueeze(0))
        predicted = (prediction.numpy()[0] * GRID).round().astype(int)
        candidate = (int(np.clip(predicted[0], 0, GRID - 1)), int(np.clip(predicted[1], 0, GRID - 1)))
        # A cell cannot be entered through a wall or teleported across the map;
        # enforce the known movement constraint so one wrong step cannot trap
        # the avatar in a corner.
        adjacent = abs(candidate[0] - player[0]) + abs(candidate[1] - player[1]) <= 1
        if adjacent and wall[candidate[1], candidate[0]] == 0:
            player = candidate
        truth = states[args.episode, step + 1]
        exact += player == (int(truth[0]), int(truth[1]))
        draw.player = player
        draw.enemies = entities(truth, 2, 4)
        draw.diamonds = entities(truth, 10, 8)
        draw.goal = (int(truth[26]), int(truth[27]))
        dream = draw.render()
        strip = np.concatenate([real, dream], axis=1)
        from PIL import Image
        Image.fromarray(strip).save(args.out / f"step-{step:04d}.png")
        if (step + 1) % 100 == 0:
            print(f"step {step + 1}/{args.steps}", flush=True)
    print(f"avatar exact over {args.steps} steps: {exact / args.steps:.3f}")
    np.array([0, 0, 0, 0] + [int(a) for a in actions[args.episode, :args.steps]], dtype=np.uint8).tofile(
        args.out / "actions.bin"
    )


if __name__ == "__main__":
    main()
